# Pagination helpers — story 8.5
#
# nextToken is the base64-encoded JSON of DynamoDB's LastEvaluatedKey.
# Both functions are pure (no I/O, no side effects) so they are trivially
# unit-testable without any AWS credentials or mocking.
# ---------------------------------------------------------------------------


def _encode_next_token(last_evaluated_key: dict | None) -> str | None:
    """Encode a DynamoDB LastEvaluatedKey into an opaque base64 nextToken string.

    Args:
        last_evaluated_key: The LastEvaluatedKey dict returned by a DynamoDB Query,
            or None when there are no more pages.

    Returns:
        Base64-encoded JSON string when last_evaluated_key is not None, else None.
    """
    if last_evaluated_key is None:
        return None
    raw_json = json.dumps(last_evaluated_key, separators=(",", ":"))
    return base64.b64encode(raw_json.encode("utf-8")).decode("ascii")


def _decode_next_token(token: str | None) -> dict | None:
    """Decode an opaque nextToken string back into a DynamoDB ExclusiveStartKey.

    Args:
        token: A base64 nextToken string from a previous MessageConnection
            response, or None to start from the beginning.

    Returns:
        Dict suitable for use as DynamoDB ExclusiveStartKey, or None when
        token is None (no cursor — start from the beginning).
    """
    if token is None:
        return None
    raw_json = base64.b64decode(token.encode("ascii")).decode("utf-8")
    return json.loads(raw_json)


def _get_dynamodb():
    """Return a (possibly cached) boto3 DynamoDB client."""
    global _dynamodb_client
    if _dynamodb_client is None:
        import boto3

        _dynamodb_client = boto3.client("dynamodb")
    return _dynamodb_client


def _get_conn():
    """Return a (possibly cached) Aurora psycopg2 connection."""
    global _conn
    if _conn is None or _conn.closed:
        _conn = knotify_db.get_connection(_DB_SECRET_NAME)
    return _conn


# ---------------------------------------------------------------------------
# Idempotency token — pure function, testable in isolation
# ---------------------------------------------------------------------------


def derive_client_request_token(
    sender_id: str,
    room_id: str,
    content: str,
    epoch_second: int,
) -> str:
    """Compute the deterministic ClientRequestToken for a sendMessage TransactWriteItems call.

    The token is a SHA-256 hex digest of the pipe-separated concatenation of
    (sender_id, room_id, content, epoch_second).  Retries that arrive within
    the same wall-clock second produce an identical token, so DynamoDB's
    10-minute idempotency window deduplicates duplicate TransactWriteItems calls
    at the service layer without any client-visible idempotency argument.

    Why SHA-256?  It is deterministic, collision-resistant, and available in
    Python's standard library — no extra dependency required.

    Args:
        sender_id:    Cognito sub of the message sender (server-set from JWT).
        room_id:      ChatRooms PK for the target room.
        content:      Message body as submitted by the caller.
        epoch_second: Floor of the current UTC epoch (seconds).  Injected by
                      the caller (not read here) so unit tests can exercise
                      determinism without depending on the system clock.

    Returns:
        64-character lowercase hex SHA-256 digest.
    """
    raw = f"{sender_id}|{room_id}|{content}|{epoch_second}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Minimal ULID generator (no new pip dependency)
#
# A ULID is a 26-character Crockford Base32 string encoding 128 bits:
#   - 48 bits: millisecond-precision Unix timestamp
#   - 80 bits: cryptographic randomness
#
# This implementation is intentionally minimal — just enough for the SK
# requirement SK = "<iso-timestamp>#<ulid>" in ChatMessages.  Full ULID
# spec: https://github.com/ulid/spec
# ---------------------------------------------------------------------------

_CROCKFORD_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def _generate_ulid() -> str:
    """Generate a new ULID string (26 uppercase Crockford Base32 characters).

    The ULID encodes the current millisecond timestamp in the first 10 chars
    and 80 bits of cryptographic randomness in the remaining 16 chars.

    Returns:
        26-character ULID string (e.g. '01ARZ3NDEKTSV4RRFFQ69G5FAV').
    """
    # Timestamp component: 48-bit millisecond epoch → 10 base-32 chars
    ts_ms = int(time.time() * 1000)
    ts_chars: list[str] = []
    remaining = ts_ms
    for _ in range(10):
        ts_chars.append(_CROCKFORD_ALPHABET[remaining & 0x1F])
        remaining >>= 5
    ts_chars.reverse()

    # Randomness component: 80 bits → 16 base-32 chars
    rand_bits = random.getrandbits(80)
    rand_chars: list[str] = []
    for _ in range(16):
        rand_chars.append(_CROCKFORD_ALPHABET[rand_bits & 0x1F])
        rand_bits >>= 5
    rand_chars.reverse()

    return "".join(ts_chars) + "".join(rand_chars)


