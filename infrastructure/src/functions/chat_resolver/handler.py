# sendMessage handler — §5.4 / story 8.4
# ---------------------------------------------------------------------------


def _handle_send_message(event: dict) -> dict:
    """
    Implement the sendMessage mutation.

    Steps:
      1. Extract sender_id from identity.sub (NEVER from GraphQL arguments).
         Extract room_id and content from arguments.
      2. GetItem ChatRoomMembership(sender_id, room_id) — reject Unauthorized
         if the row is absent (sender is not a member).
      3. GetItem ChatRooms(room_id) — reject RoomDeactivated if status != 'active';
         reject RoomReadOnly if friendship_active != true.
      4. Compute SK = "<iso-timestamp>#<ulid>" (server-set delivered_at).
      5. Compute ClientRequestToken = derive_client_request_token(sender_id,
         room_id, content, floor(time.time())).  Retries within the same
         wall-clock second carry an identical token and are deduplicated by
         DynamoDB's 10-minute idempotency window.
      6. TransactWriteItems:
           - PutItem ChatMessages (room_id PK, SK, sender_id, content,
             content_type, delivered_at).
           - UpdateItem ChatRooms (last_message_id, last_message_at,
             last_message_preview, last_message_sender_id).
         No Notifications row is written — chat messages are NOT logged to the
         Notifications table (§5.4.2 explicit rule).

    Args:
        event: AppSync Lambda resolver event dict.

    Returns:
        Message dict on success, or an error dict on failure.
    """
    sender_id: str = event.get("identity", {}).get("sub", "")
    arguments: dict = event.get("arguments", {})
    room_id: str = arguments.get("roomId", "")
    content: str = arguments.get("content", "")
    content_type: str = arguments.get("contentType", "text")

    ddb = _get_dynamodb()

    # 2. Membership check — sender must be in the room.
    membership_resp = ddb.get_item(
        TableName="ChatRoomMembership",
        Key={
            "user_id": {"S": sender_id},
            "room_id": {"S": room_id},
        },
    )
    if "Item" not in membership_resp:
        return _unauthorized_response(REASON_NOT_FRIENDS)

    # 3. Room status + friendship_active check.
    room_resp = ddb.get_item(
        TableName="ChatRooms",
        Key={"room_id": {"S": room_id}},
    )
    room_item = room_resp.get("Item", {})
    room_status: str = room_item.get("status", {}).get("S", "")
    friendship_active: bool = room_item.get("friendship_active", {}).get("BOOL", False)

    if room_status != "active":
        return {
            "errorType": "RoomDeactivated",
            "message": "The chat room is deactivated.",
            "reason": REASON_ROOM_DEACTIVATED,
        }
    if not friendship_active:
        return {
            "errorType": "RoomReadOnly",
            "message": "The chat room is read-only (friendship inactive).",
            "reason": REASON_ROOM_READ_ONLY,
        }

    # 4. Build SK: "<iso-timestamp>#<ulid>".
    now = datetime.now(tz=timezone.utc)
    delivered_at: str = now.isoformat()
    ulid: str = _generate_ulid()
    message_sk: str = f"{delivered_at}#{ulid}"

    # 5. Deterministic idempotency token — epoch_second injected (not read
    #    inside derive_client_request_token) so the function stays pure.
    epoch_second: int = int(time.time())
    client_request_token: str = derive_client_request_token(
        sender_id=sender_id,
        room_id=room_id,
        content=content,
        epoch_second=epoch_second,
    )

    # Preview truncated to 80 chars for the room-list UI (§5.4 architecture).
    preview: str = content[:80]

    # 6. Atomic write: ChatMessages PutItem + ChatRooms UpdateItem.
    #    No Notifications row — §5.4.2 explicit rule.
    transact_items = [
        {
            "Put": {
                "TableName": "ChatMessages",
                "Item": {
                    "room_id": {"S": room_id},
                    "sk": {"S": message_sk},
                    "sender_id": {"S": sender_id},
                    "content": {"S": content},
                    "content_type": {"S": content_type},
                    "delivered_at": {"S": delivered_at},
                },
            }
        },
        {
            "Update": {
                "TableName": "ChatRooms",
                "Key": {"room_id": {"S": room_id}},
                "UpdateExpression": (
                    "SET last_message_id = :msg_id, "
                    "last_message_at = :msg_at, "
                    "last_message_preview = :preview, "
                    "last_message_sender_id = :sender"
                ),
                "ExpressionAttributeValues": {
                    ":msg_id": {"S": message_sk},
                    ":msg_at": {"S": delivered_at},
                    ":preview": {"S": preview},
                    ":sender": {"S": sender_id},
                },
            }
        },
    ]

    ddb.transact_write_items(
        TransactItems=transact_items,
        ClientRequestToken=client_request_token,
    )

    logger.info(
        "send_message_success",
        extra={
            "room_id": room_id,
            "sender_id": sender_id,
            "message_sk": message_sk,
        },
    )

    # Response fields match the GraphQL Message type in schema.graphql (story 8.2):
    #   roomId, createdAt, messageId, senderId, content, contentType, deliveredAt.
    # messageId = the full SK value (<iso>#<ulid>) which AppSync clients use as a
    # cursor and which the subscription field filter targets.
    # createdAt mirrors deliveredAt (server-set timestamp); both are the same moment.
    return {
        "roomId": room_id,
        "messageId": message_sk,
        "createdAt": delivered_at,
        "senderId": sender_id,
        "content": content,
        "contentType": content_type,
        "deliveredAt": delivered_at,
    }


