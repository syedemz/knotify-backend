def _decode_message(item: dict) -> dict:
    """Decode a DynamoDB ChatMessages item into a plain dict matching Message type.

    The ChatMessages table SK is the "sk" attribute (written by sendMessage as
    "<iso-timestamp>#<ulid>").  The "createdAt" field mirrors the ISO timestamp
    prefix of the SK; "messageId" is the full SK value used as a cursor.

    Args:
        item: A single ChatMessages DynamoDB item.

    Returns:
        Message dict with camelCase keys matching the GraphQL Message type.
    """
    sk_value = item.get("sk", {}).get("S", "")
    # createdAt is the ISO timestamp prefix (before the '#' separator)
    created_at = sk_value.split("#")[0] if "#" in sk_value else sk_value
    return {
        "roomId": item.get("room_id", {}).get("S", ""),
        "messageId": sk_value,
        "createdAt": created_at,
        "senderId": item.get("sender_id", {}).get("S", ""),
        "content": item.get("content", {}).get("S", ""),
        "contentType": item.get("content_type", {}).get("S", "text"),
        "gifUrl": item.get("gif_url", {}).get("S"),
        "deliveredAt": item.get("delivered_at", {}).get("S", ""),
    }


def _handle_messages_by_chat_room(event: dict) -> dict:
    """
    Implement the messagesByChatRoom Query.

    Steps:
      1. GetItem(ChatRoomMembership, (identity.sub, roomId)) — reject Unauthorized
         if the caller is not a member of the room.
      2. Query(ChatMessages, PK=roomId, ScanIndexForward=False) — descending by SK
         (newest first). Apply SK condition > createdAtGt when supplied.
         Apply limit (default _MESSAGES_DEFAULT_LIMIT, cap _MESSAGES_MAX_LIMIT).
         Resume from nextToken (ExclusiveStartKey) when supplied.
      3. Encode DynamoDB LastEvaluatedKey into a nextToken for the response.

    Args:
        event: AppSync Lambda resolver event dict.

    Returns:
        MessageConnection dict: {"items": [Message, ...], "nextToken": str | None}
    """
    caller_id: str = event.get("identity", {}).get("sub", "")
    arguments: dict = event.get("arguments", {})
    room_id: str = arguments.get("roomId", "")
    created_at_gt: str | None = arguments.get("createdAtGt")
    client_limit: int | None = arguments.get("limit")
    next_token_in: str | None = arguments.get("nextToken")

    ddb = _get_dynamodb()

    # 1. Membership check: caller must be in the room.
    membership_resp = ddb.get_item(
        TableName="ChatRoomMembership",
        Key={
            "user_id": {"S": caller_id},
            "room_id": {"S": room_id},
        },
    )
    if "Item" not in membership_resp:
        return _unauthorized_response(REASON_NOT_FRIENDS)

    # 2. Compute effective limit.
    #    Default: _MESSAGES_DEFAULT_LIMIT (20).
    #    Defensive cap: _MESSAGES_MAX_LIMIT (100) — silently clamp any larger
    #    client-supplied value. This prevents excessive DynamoDB reads from a
    #    misconfigured or malicious client.
    effective_limit = _MESSAGES_DEFAULT_LIMIT
    if client_limit is not None:
        effective_limit = min(int(client_limit), _MESSAGES_MAX_LIMIT)

    # 3. Build DynamoDB Query parameters.
    query_kwargs: dict = {
        "TableName": "ChatMessages",
        "KeyConditionExpression": "room_id = :rid",
        "ExpressionAttributeValues": {":rid": {"S": room_id}},
        "ScanIndexForward": False,  # descending by SK (newest messages first)
        "Limit": effective_limit,
    }

    # Optional SK lower-bound filter: SK > createdAtGt
    # createdAtGt is an ISO timestamp prefix. Since the SK format is
    # "<iso-timestamp>#<ulid>", a begins_with or > comparison on the prefix
    # returns all messages created after the given timestamp.
    if created_at_gt:
        query_kwargs["KeyConditionExpression"] += (
            " AND sk > :cat_gt"
        )
        query_kwargs["ExpressionAttributeValues"][":cat_gt"] = {"S": created_at_gt}

    # Optional pagination cursor.
    exclusive_start_key = _decode_next_token(next_token_in)
    if exclusive_start_key is not None:
        query_kwargs["ExclusiveStartKey"] = exclusive_start_key

    messages_resp = ddb.query(**query_kwargs)
    raw_items = messages_resp.get("Items", [])
    last_evaluated_key = messages_resp.get("LastEvaluatedKey")

    messages = [_decode_message(item) for item in raw_items]
    next_token_out = _encode_next_token(last_evaluated_key)

    logger.info(
        "messages_by_chat_room_success",
        extra={
            "caller_id": caller_id,
            "room_id": room_id,
            "message_count": len(messages),
            "has_next_page": next_token_out is not None,
        },
    )

    # Return matches MessageConnection type in schema.graphql:
    #   { items: [Message!]!, nextToken: String }
    return {
        "items": messages,
        "nextToken": next_token_out,
    }


# ---------------------------------------------------------------------------
# AppSync resolver dispatcher
#
# The single entry point for all (typeName, fieldName) pairs routed to this
# Lambda via the AppSync data source configuration.
#
# Return value conventions for AppSync Lambda resolvers:
#   Success  → any serialisable dict / list (AppSync merges it into the
#               GraphQL response data).
#   Error    → {"errorType": "<ErrorCode>", "message": "<human-readable>",
#               "reason": "<machine-code>"}  — AppSync surfaces these as
#               GraphQL errors with extensions.errorType and extensions.reason.
# ---------------------------------------------------------------------------


def _dispatch(event: dict) -> Any:
    """
    Route the AppSync resolver event to the appropriate sub-handler.

    Wired so far:
        (Mutation, createOrGetRoom)      → _handle_create_or_get_room  [story 8.3]
        (Mutation, sendMessage)          → _handle_send_message         [story 8.4]
        (Query,    listMyRooms)          → _handle_list_my_rooms        [story 8.5]
        (Query,    messagesByChatRoom)   → _handle_messages_by_chat_room [story 8.5]

    Later stories add:
        ...

    Args:
        event: AppSync Lambda resolver event dict.

    Returns:
        A dict that AppSync merges into the GraphQL response.
    """
    type_name: str = event.get("typeName", "")
    field_name: str = event.get("fieldName", "")

    logger.info(
        "chat_resolver_dispatch",
        extra={"type_name": type_name, "field_name": field_name},
    )

    if type_name == "Mutation" and field_name == "createOrGetRoom":
        return _handle_create_or_get_room(event)

    if type_name == "Mutation" and field_name == "sendMessage":
        return _handle_send_message(event)

    if type_name == "Query" and field_name == "listMyRooms":
        return _handle_list_my_rooms(event)

    if type_name == "Query" and field_name == "messagesByChatRoom":
        return _handle_messages_by_chat_room(event)

    return {
        "errorType": "Unimplemented",
        "message": f"{type_name}.{field_name} not yet implemented",
    }


